"""
Generate project metadata and conda compatibility files.

Source of truth:
- src/heavenbase/version.py
- requirements.txt
- requirements-dev.txt
- requirements-interop.txt
- requirements-daft.txt
- requirements-sql.txt
- requirements-full.txt

pyproject.toml reads those files through setuptools dynamic metadata.
The package version projects into Poetry metadata and the generated header of every
built-in ``meta.yaml``. ``scripts/sync-env.bash`` also refreshes uv.lock,
poetry.lock, and conda adapters.

Tool priority for installs (highest to lowest):
1. uv        — uv.lock + `uv sync`
2. pip       — requirements*.txt + `pip install -e ".[dev]"`
3. pyproject — `pip install -e ".[dev]"` when only pyproject metadata is available
4. conda     — environment-*.yml with `-e ".[<extra>]"`

Usage:
    python scripts/sync-env.py
    python scripts/sync-env.py --check
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

_VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)\.(\d+)(?:dev(\d+))?$")
_COORDINATE_RE = re.compile(r"^heavenbase(?:/[a-z0-9][a-z0-9_-]*)+$")
_MANIFEST_HEADER_RE = re.compile(
    r"\Amanifest_version:[ \t]*(?P<manifest_version>[^\r\n]+)\r?\n"
    r"coordinate:[ \t]*(?P<coordinate>[^\r\n]+)\r?\n"
    r"version:[ \t]*(?P<version>[^\r\n]+)\r?\n"
    r"compatibility:[ \t]*\{[ \t]*heavenbase:[ \t]*\{[ \t]*min:[ \t]*(?P<minimum>[^,}\r\n]+)[ \t]*,"
    r"[ \t]*before:[ \t]*(?P<before>[^}\r\n]+?)[ \t]*\}[ \t]*\}[ \t]*(?P<newline>\r?\n)"
)

_SOURCE_REQUIREMENTS = (
    "requirements.txt",
    "requirements-dev.txt",
    "requirements-interop.txt",
    "requirements-daft.txt",
    "requirements-sql.txt",
    "requirements-full.txt",
)

_OPTIONAL_FILES = {
    "dev": "requirements-dev.txt",
    "interop": "requirements-interop.txt",
    "daft": "requirements-daft.txt",
    "sql": "requirements-sql.txt",
    "full": "requirements-full.txt",
}

_EXTRAS_MAP = {
    "full": ("heavenbase", "environment.yml"),
    "dev": ("heavenbase-dev", "environment-dev.yml"),
    "sql": ("heavenbase-sql", "environment-sql.yml"),
    "interop": ("heavenbase-interop", "environment-interop.yml"),
    "daft": ("heavenbase-daft", "environment-daft.yml"),
}

_CONDA_HEADER = """\
# Generated by scripts/sync-env.py — do not edit.
# Edit requirements*.txt, then run bash scripts/sync-env.bash
"""

_CONDA_TEMPLATE = """\
{_header}name: {name}
channels:
  - conda-forge
  - defaults
dependencies:
  - python {python_ver}
  - pip
  - pip:
    - -e ".[{extra}]"
"""


def _project_name(pyproject_text: str) -> str:
    match = re.search(r'^name = "([^"]+)"', pyproject_text, re.M)
    if not match:
        raise ValueError("missing [project].name in pyproject.toml")
    return match.group(1)


def _python_pin(pyproject_text: str) -> str:
    path = ROOT / ".python-version"
    if path.exists():
        return path.read_text(encoding="utf-8").strip()
    match = re.search(r'requires-python\s*=\s*"([^"]+)"', pyproject_text)
    return match.group(1) if match else ">=3.10,<3.14"


def _package_version(root: Path = ROOT) -> str:
    version_py = root / "src" / "heavenbase" / "version.py"
    match = re.search(r'__version__\s*=\s*"([^"]+)"', version_py.read_text(encoding="utf-8"))
    if not match:
        raise ValueError(f"missing __version__ in {version_py}")
    version = match.group(1)
    _compatibility_before(version)
    return version


def _compatibility_before(version: str) -> str:
    """Return the exclusive next-train bound for a HeavenBase version."""
    match = _VERSION_RE.fullmatch(version)
    if match is None:
        raise ValueError(f"package version must use MAJOR.MINOR.PATCH.N[devK], got {version!r}")
    numeric = match.groups()[:4]
    development = match.group(5)
    if any(str(int(part)) != part for part in numeric) or (development is not None and str(int(development)) != development):
        raise ValueError(f"package version must be canonical, got {version!r}")
    major, minor, patch = (int(part) for part in numeric[:3])
    return f"{major}.{minor}.{patch + 1}.0"


def _sync_poetry_version(pyproject_text: str, version: str) -> str:
    lines: list[str] = []
    in_poetry = False
    found = 0
    for line in pyproject_text.splitlines():
        if line.strip() == "[tool.poetry]":
            in_poetry = True
        elif line.startswith("[") and in_poetry:
            in_poetry = False
        if in_poetry and line.startswith("version = "):
            line = f'version = "{version}"'
            found += 1
        lines.append(line)
    if found != 1:
        raise ValueError(f"pyproject.toml must contain exactly one [tool.poetry].version, found {found}")
    return "\n".join(lines) + "\n"


def _project_manifest_header(text: str, version: str, path: Path) -> tuple[str, str]:
    """Project package-owned fields while preserving the manifest body."""
    match = _MANIFEST_HEADER_RE.match(text)
    if match is None:
        raise ValueError(f"{path} must begin with the generated manifest_version, coordinate, version, and inline compatibility header")
    if match.group("manifest_version").strip() != "2":
        raise ValueError(f"{path} manifest_version must be 2")
    coordinate = match.group("coordinate").strip()
    if _COORDINATE_RE.fullmatch(coordinate) is None:
        raise ValueError(f"{path} coordinate must be a lowercase heavenbase/... coordinate, got {coordinate!r}")
    newline = match.group("newline")
    before = _compatibility_before(version)
    header = newline.join(
        (
            "manifest_version: 2",
            f"coordinate: {coordinate}",
            f"version: {version}",
            f"compatibility: {{heavenbase: {{min: {version}, before: {before}}}}}",
            "",
        )
    )
    return coordinate, header + text[match.end() :]


def builtin_manifest_projection(package_root: Path, version: str) -> dict[Path, str]:
    """Return expected text for every built-in module descriptor.

    Only the generated four-line header is normalized. Everything after that
    header is retained exactly, including comments and author-owned YAML style.

    Args:
        package_root: Root of the packaged HeavenBase source tree.
        version: Canonical package version to project.

    Returns:
        dict[Path, str]: Expected descriptor text keyed by source path.

    Raises:
        ValueError: If no descriptors exist or a header, coordinate, version,
            or coordinate inventory is invalid.
    """
    paths = sorted(path for path in package_root.rglob("meta.yaml") if path.is_file())
    if not paths:
        raise ValueError(f"no built-in meta.yaml files found below {package_root}")
    projected: dict[Path, str] = {}
    coordinates: dict[str, Path] = {}
    for path in paths:
        coordinate, text = _project_manifest_header(path.read_text(encoding="utf-8"), version, path)
        previous = coordinates.get(coordinate)
        if previous is not None:
            raise ValueError(f"built-in coordinate {coordinate!r} is repeated by {previous} and {path}")
        coordinates[coordinate] = path
        projected[path] = text
    return projected


def version_metadata_projection(root: Path = ROOT, version: str | None = None) -> dict[Path, str]:
    """Return every package-version projection without mutating the tree.

    Args:
        root: Repository root containing pyproject.toml and ``src/heavenbase``.
        version: Version to project. Defaults to ``src/heavenbase/version.py``.

    Returns:
        dict[Path, str]: Expected Poetry and module-descriptor text by path.

    Raises:
        ValueError: If the version or a projection target is malformed.
    """
    package_version = _package_version(root) if version is None else version
    _compatibility_before(package_version)
    pyproject = root / "pyproject.toml"
    projection = {pyproject: _sync_poetry_version(pyproject.read_text(encoding="utf-8"), package_version)}
    projection.update(builtin_manifest_projection(root / "src" / "heavenbase", package_version))
    return projection


def sync_version_metadata(root: Path = ROOT, *, check: bool = False) -> tuple[str, ...]:
    """Synchronize or report package-version projections.

    Args:
        root: Repository root containing the version projection targets.
        check: Whether to report drift without writing it.

    Returns:
        tuple[str, ...]: Repository-relative paths that differed on entry.

    Raises:
        ValueError: If the version or a projection target is malformed.
    """
    projection = version_metadata_projection(root)
    drift = tuple(path.relative_to(root).as_posix() for path, expected in projection.items() if path.read_text(encoding="utf-8") != expected)
    if not check:
        for path, expected in projection.items():
            if path.read_text(encoding="utf-8") == expected:
                continue
            path.write_text(expected, encoding="utf-8", newline="\n")
            print(f"  synced {path.relative_to(root).as_posix()} from src/heavenbase/version.py")
    return drift


def _validate_pyproject_wiring(pyproject_text: str) -> None:
    if 'dynamic = ["version", "dependencies", "optional-dependencies"]' not in pyproject_text:
        raise SystemExit("pyproject.toml must declare dynamic version, dependencies, and optional-dependencies")
    if 'dependencies = { file = ["requirements.txt"] }' not in pyproject_text:
        raise SystemExit("pyproject.toml must load runtime deps from requirements.txt")
    for extra, filename in _OPTIONAL_FILES.items():
        needle = f'optional-dependencies.{extra} = {{ file = ["{filename}"] }}'
        if needle not in pyproject_text:
            raise SystemExit(f"pyproject.toml must load extra '{extra}' from {filename}")
    if re.search(r"^\s*dependencies\s*=\s*\[", pyproject_text, re.M):
        raise SystemExit("pyproject.toml must not inline [project].dependencies; edit requirements.txt")
    if re.search(r"^\s*\[project\.optional-dependencies\]", pyproject_text, re.M):
        raise SystemExit("pyproject.toml must not inline optional-dependencies; edit requirements-*.txt")


def _validate_requirements_sources() -> None:
    missing: list[str] = []
    empty: list[str] = []
    for filename in _SOURCE_REQUIREMENTS:
        path = ROOT / filename
        if not path.exists():
            missing.append(filename)
            continue
        lines = [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip() and not line.strip().startswith("#")]
        if not lines:
            empty.append(filename)
    if missing:
        raise SystemExit(f"Missing requirements source file(s): {', '.join(missing)}")
    if empty:
        raise SystemExit(f"Requirements source file(s) have no dependency lines: {', '.join(empty)}")


def _declared_extras(pyproject_text: str) -> set[str]:
    return set(re.findall(r"optional-dependencies\.(\w+)\s*=", pyproject_text))


def _expected_conda_files(pyproject_text: str) -> dict[str, str]:
    python_ver = _python_pin(pyproject_text)
    declared = _declared_extras(pyproject_text)
    expected: dict[str, str] = {}
    for extra, (env_name, filename) in _EXTRAS_MAP.items():
        if extra not in declared and extra != "full":
            continue
        expected[filename] = _CONDA_TEMPLATE.format(
            _header=_CONDA_HEADER,
            name=env_name,
            extra=extra,
            python_ver=python_ver,
        )
    return expected


def generate(check: bool = False) -> None:
    pyproject_path = ROOT / "pyproject.toml"
    pyproject_text = pyproject_path.read_text(encoding="utf-8")
    _validate_pyproject_wiring(pyproject_text)
    _validate_requirements_sources()
    version_drift = sync_version_metadata(ROOT, check=check)
    if not check and "pyproject.toml" in version_drift:
        pyproject_text = pyproject_path.read_text(encoding="utf-8")

    expected_files = _expected_conda_files(pyproject_text)
    out_of_date = list(version_drift)

    for filename, expected in expected_files.items():
        path = ROOT / filename
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                out_of_date.append(filename)
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
            print(f"  wrote {filename}")

    unmapped = _declared_extras(pyproject_text) - set(_EXTRAS_MAP)
    for extra in sorted(unmapped):
        print(f"  [warn] extras '{extra}' has no environment mapping; add it to _EXTRAS_MAP", file=sys.stderr)

    if check:
        if out_of_date:
            print(f"Generated metadata or compatibility files out of date: {', '.join(out_of_date)}", file=sys.stderr)
            print("Run: bash scripts/sync-env.bash", file=sys.stderr)
            sys.exit(1)
        print("Generated metadata and compatibility files are up to date.")
        return

    print("[sync-env] generated metadata and conda compatibility files refreshed")


if __name__ == "__main__":
    generate(check="--check" in sys.argv)
