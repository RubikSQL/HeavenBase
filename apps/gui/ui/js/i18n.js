let lang = localStorage.getItem("hb-lang") === "zh" ? "zh" : "en";
export function currentLang() {
    return lang;
}
export function setLang(next) {
    lang = next === "zh" ? "zh" : "en";
    localStorage.setItem("hb-lang", lang);
}
// t("Copy {name}", {name: "title"}) — English text is the key; zh falls back to en when unmapped.
export function t(text, vars) {
    let out = lang === "zh" ? (ZH[text] ?? text) : text;
    if (vars)
        out = out.replace(/\{(\w+)\}/g, (_match, key) => String(vars[key] ?? ""));
    return out;
}
